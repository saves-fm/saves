import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:sentry_flutter/sentry_flutter.dart';

// Public by design: a Sentry DSN only lets the app send errors to the
// saves-mobile project.
const sentryDsn =
    'https://b448cb4251328a20dbf28a4a97ad7831@o4512393096134656.ingest.us.sentry.io/4512393109504000';

// Errors only: no screenshots, view hierarchy, session replay or tracing, and
// no personal data, in line with the privacy policy. Off in debug builds.
Future<void> main() async {
  if (kDebugMode) {
    runApp(const SavesApp());
    return;
  }
  await SentryFlutter.init(
    (options) {
      options.dsn = sentryDsn;
      options.sendDefaultPii = false;
      options.attachScreenshot = false;
      options.attachViewHierarchy = false;
      options.tracesSampleRate = 0;
    },
    appRunner: () => runApp(const SavesApp()),
  );
}

// Placeholder until the app shell lands in v2.0.0. The theme will come from
// the Dart file generated by packages/tokens (v0.2.0), not hardcoded colors.
class SavesApp extends StatelessWidget {
  const SavesApp({super.key});

  @override
  Widget build(BuildContext context) {
    return const MaterialApp(
      title: 'saves.fm',
      home: Scaffold(
        body: Center(child: Text('saves.fm')),
      ),
    );
  }
}
